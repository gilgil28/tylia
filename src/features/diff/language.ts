/** Picks a grammar for `path` (either separator), or `null` to show plain text. */
export function detectLanguage(path: string): HighlightLang | null {
  const name = path.slice(Math.max(path.lastIndexOf("/"), path.lastIndexOf("\\")) + 1);
  const lower = name.toLowerCase();
  const exact = BY_NAME[lower];
  if (exact) return exact;
  // `Dockerfile.dev` (`build.Dockerfile` is covered by the extension map)
  if (lower.startsWith("dockerfile.")) return "docker";
  const dot = lower.lastIndexOf(".");
  if (dot <= 0) return null;
  return BY_EXTENSION[lower.slice(dot + 1)] ?? null;
}
